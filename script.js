const documentTitles = {
  sk: "Dutch Transport Group Slovakia | Medzinárodná logistika",
  en: "Dutch Transport Group Slovakia | International Logistics",
};

const menuToggle = document.querySelector(".menu-toggle");
const navLinks = document.querySelector("#navLinks");
const languageButtons = document.querySelectorAll(".lang-btn");
const quoteForm = document.querySelector("#quoteForm");

let activeLanguage = localStorage.getItem("dtg-language") || "sk";

function setLanguage(lang) {
  activeLanguage = translations[lang] ? lang : "sk";
  document.documentElement.lang = activeLanguage;
  document.title = documentTitles[activeLanguage];

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    const value = translations[activeLanguage][key];
    if (value) {
      node.textContent = value;
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    const value = translations[activeLanguage][key];
    if (value) {
      node.setAttribute("placeholder", value);
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === activeLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("dtg-language", activeLanguage);
}

function closeMenu() {
  document.body.classList.remove("is-menu-open");
  navLinks.classList.remove("is-open");
  menuToggle.setAttribute("aria-expanded", "false");
}

menuToggle.addEventListener("click", () => {
  const isOpen = navLinks.classList.toggle("is-open");
  document.body.classList.toggle("is-menu-open", isOpen);
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});

navLinks.querySelectorAll("a").forEach((link) => {
  link.addEventListener("click", closeMenu);
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

quoteForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const formData = new FormData(quoteForm);
  const labels =
    activeLanguage === "sk"
      ? {
          subject: "Dopyt pre Dutch Transport Group Slovakia",
          name: "Meno",
          company: "Firma",
          email: "E-mail",
          route: "Trasa",
          message: "Správa",
        }
      : {
          subject: "Request for Dutch Transport Group Slovakia",
          name: "Name",
          company: "Company",
          email: "Email",
          route: "Route",
          message: "Message",
        };

  const body = [
    `${labels.name}: ${formData.get("name") || ""}`,
    `${labels.company}: ${formData.get("company") || ""}`,
    `${labels.email}: ${formData.get("email") || ""}`,
    `${labels.route}: ${formData.get("route") || ""}`,
    "",
    `${labels.message}:`,
    formData.get("message") || "",
  ].join("\n");

  const mailto = new URL("mailto:info@dutchtransportgroup.sk");
  mailto.searchParams.set("subject", labels.subject);
  mailto.searchParams.set("body", body);
  window.location.href = mailto.toString();
});

setLanguage(activeLanguage);
